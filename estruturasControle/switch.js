let dia = 1;  // Dia da semana
switch (dia) {
    case 1:
        console.log("Domingo");
        break;
    case 2:
        console.log("segunda-feira");
        break;

    case 3:   
        console.log("terca-feira");
        break;

    case 4:
        console.log("Quarta-feira");
        break;

    case 5:
        console.log("Quinta-feira");
        break;
    case 6:
        console.log("sexta-feira");
        break;
    case 7:
        console.log("Sábado");
        break;
        default:
            console.log("múmero inválido!");

}